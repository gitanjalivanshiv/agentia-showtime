import type {DemoScript, Step} from '../script/schema.js'

/**
 * Turns script.yaml into a Robot Framework (QWeb) suite. Every step ends with `LogScreenshot`, and
 * marker lines (`SHOWTIME_STEP_START:<id>` / `SHOWTIME_STEP:<id>:<True|False>`) let us map screenshots
 * back to steps from output.xml. Login happens first and is never screenshotted.
 */

const OBJECT_API: Record<string, string> = {
  accounts: 'Account',
  contacts: 'Contact',
  cases: 'Case',
  leads: 'Lead',
  opportunities: 'Opportunity',
  tasks: 'Task',
}

/** Robot separates arguments with 2+ spaces, and treats `${`, `@{`, `&{`, `%{` and `\` specially. */
export function esc(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/([$@&%])\{/g, '\\$1{')
    .replace(/\s{2,}/g, ' ')
    .replace(/\n/g, ' ')
    .replace(/^#/, '\\#')
    .trim()
}

export function stepKeyword(step: Step): string {
  const target = esc(step.target)
  const value = step.value === undefined ? undefined : esc(step.value)
  switch (step.action) {
    case 'navigate': {
      const api = OBJECT_API[step.target.trim().toLowerCase()]
      return api ? `GoTo    \${BASE}/lightning/o/${api}/list` : `ClickText    ${target}`
    }
    case 'click':
      return `ClickText    ${target}`
    case 'type':
      return `TypeText    ${target}    ${value ?? ''}`
    case 'verify':
      return `VerifyText    ${value ?? target}`
    case 'wait':
      return `Sleep    ${value ?? '2s'}`
  }
}

export interface RobotOptions {
  loginUrl: string
}

export function generateRobot(script: DemoScript, options: RobotOptions): string {
  const steps = script.steps
    .map((s) =>
      [
        `    Log    SHOWTIME_STEP_START:${s.id}`,
        `    \${ok}=    Run Keyword And Return Status    Wait Until Keyword Succeeds    2x    2s    ${stepKeyword(s)}`,
        '    Sleep    1s',
        '    LogScreenshot',
        `    Log    SHOWTIME_STEP:${s.id}:\${ok}`,
      ].join('\n'),
    )
    .join('\n')
  return `*** Settings ***
Documentation     Generated by Showtime for ${esc(script.story.name)}. Edit script.yaml, not this file.
Library           QWeb
Suite Setup       Open Browser    about:blank    chrome
Suite Teardown    Close All Browsers

*** Variables ***
\${LOGIN_URL}      ${esc(options.loginUrl)}

*** Test Cases ***
Showtime ${esc(script.story.name)}
    SetConfig    DefaultTimeout    20s
    Showtime Login
    \${url}=    GetUrl
    \${base}=    Evaluate    '/'.join('''\${url}'''.split('/')[:3])
    Set Suite Variable    \${BASE}    \${base}
${steps}

*** Keywords ***
Showtime Login
    [Documentation]    Credentials come from the CRT variables UAT_USERNAME and UAT_PASSWORD.
    GoTo    \${LOGIN_URL}
    TypeText    Username    \${UAT_USERNAME}
    ClickText    Log In to Sandbox
    Run Keyword And Ignore Error    TypeSecret    Password    \${UAT_PASSWORD}
    Run Keyword And Ignore Error    ClickText    Log In
    Wait Until Keyword Succeeds    12x    5s    Showtime On Lightning

Showtime On Lightning
    \${now}=    GetUrl
    Should Contain    \${now}    lightning
`
}
